/** Looks up a dotted key ("kinds.skill") in the chosen language, then English, then returns the key. */
export function makeT(lang) {
  const get = (l, key) => key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), DICT[l]);
  return (key, vars) => {
    let s = get(lang, key);
    if (typeof s !== 'string') s = get('en', key);
    if (typeof s !== 'string') return key;
    return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k]))) : s;
  };
}

/** Card text: chosen language, then English, then the fallback (raw name or description). */
export function pick(loc, lang, fallback) {
  if (loc && typeof loc === 'object') {
    if (loc[lang]) return loc[lang];
    if (loc.en) return loc.en;
  }
  return fallback;
}
